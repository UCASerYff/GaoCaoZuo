import Foundation

/// Polling cannot identify every pasteboard producer. These observations only
/// authorize this one unchanged read; they never retrospectively authorize a
/// change observed while secure input was active.
enum ClipboardCollectionPolicy {
    struct Context: Equatable {
        let pid: Int32
        let bundleID: String
        let launchIdentity: String?
        let secureInput: Bool
        let secureField: Bool
        let excluded: Bool
        var permitsCapture: Bool {
            pid > 0 && !bundleID.isEmpty && launchIdentity != nil
                && !secureInput && !secureField && !excluded
        }
    }

    static let sensitiveApps: Set<String> = [
        "com.agilebits.onepassword", "com.1password.1password", "com.bitwarden.desktop",
        "org.keepassxc.keepassxc", "com.enpass.enpass", "com.apple.keychainaccess", "com.apple.passwords"
    ]
    static let prohibitedTypePrefixes = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"
    ]
    static func isProhibitedType(_ type: String) -> Bool {
        prohibitedTypePrefixes.contains(where: type.hasPrefix)
    }
    static func begin(changeCount: Int, previous: inout Int, context: Context) -> Bool {
        guard changeCount != previous else { return false }
        // Consume even an unsafe observation. Leaving it pending would capture
        // a password copied under secure input after secure input turns off.
        previous = changeCount
        return context.permitsCapture
    }
    static func permitsCommit(before: Context, after: Context, readCount: Int, currentCount: Int) -> Bool {
        before.permitsCapture && after.permitsCapture && before == after && readCount == currentCount
    }
}
